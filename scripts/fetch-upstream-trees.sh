#!/usr/bin/env bash
# Fetch pinned easybuilders trees for the ignored real-tree tests.
#
# Read-only: clone and checkout only. The pins are the latest 5.x release
# (v5.4.1) and the develop commit recorded with that release check.
#
# Usage: scripts/fetch-upstream-trees.sh [cache-dir]
# Default cache: ${EB_UPSTREAM_CACHE:-$HOME/.cache/eb-stack/upstream}
# Writes <cache>/env.sh. Source it before
#   cargo test --locked --all-targets -- --include-ignored

set -euo pipefail

cache=${1:-${EB_UPSTREAM_CACHE:-${HOME}/.cache/eb-stack/upstream}}
mkdir -p "$cache/mirrors"

# Peeled annotated-tag commits, and develop as of 2026-10-24.
EC_URL=https://github.com/easybuilders/easybuild-easyconfigs.git
EC_TAG=easybuild-easyconfigs-v5.4.1
EC_TAG_COMMIT=5cc85e8a07a468385ac7157892be86462e7d3285
EC_DEVELOP=981d2123dddccca9ce0b15f9eb2643e872332f5e

BLOCKS_URL=https://github.com/easybuilders/easybuild-easyblocks.git
BLOCKS_TAG=easybuild-easyblocks-v5.4.1
BLOCKS_TAG_COMMIT=9607addb10e02da5e3f44916a0be6222f9795287

FRAMEWORK_URL=https://github.com/easybuilders/easybuild-framework.git
FRAMEWORK_TAG=easybuild-framework-v5.4.1
FRAMEWORK_TAG_COMMIT=2ca2297fd47ce1838b61b30d779c3b00b6d0e61c

ensure_mirror() {
  local url=$1 name=$2
  local mirror=$cache/mirrors/$name
  if [[ ! -d "$mirror/.git" ]]; then
    git clone --filter=blob:none --no-checkout "$url" "$mirror"
  fi
  printf '%s\n' "$mirror"
}

checkout() {
  local mirror=$1 commit=$2 dest=$3
  if [[ -d "$dest" ]]; then
    local head
    head=$(git -C "$dest" rev-parse HEAD)
    if [[ $head != "$commit" ]]; then
      echo "checkout $dest is $head, want $commit" >&2
      exit 1
    fi
    return
  fi
  git -C "$mirror" worktree add --detach "$dest" "$commit"
}

ec=$(ensure_mirror "$EC_URL" easybuild-easyconfigs)
git -C "$ec" fetch --no-tags origin "$EC_DEVELOP"
git -C "$ec" fetch origin "refs/tags/${EC_TAG}:refs/tags/${EC_TAG}"
git -C "$ec" update-ref refs/heads/develop "$EC_DEVELOP"
test "$(git -C "$ec" rev-parse "${EC_TAG}^{commit}")" = "$EC_TAG_COMMIT"
test "$(git -C "$ec" rev-parse refs/heads/develop)" = "$EC_DEVELOP"
checkout "$ec" "$EC_DEVELOP" "$cache/easybuild-easyconfigs-develop"
checkout "$ec" "$EC_TAG_COMMIT" "$cache/easybuild-easyconfigs-v5.4.1"

blocks=$(ensure_mirror "$BLOCKS_URL" easybuild-easyblocks)
git -C "$blocks" fetch origin "refs/tags/${BLOCKS_TAG}:refs/tags/${BLOCKS_TAG}"
test "$(git -C "$blocks" rev-parse "${BLOCKS_TAG}^{commit}")" = "$BLOCKS_TAG_COMMIT"
checkout "$blocks" "$BLOCKS_TAG_COMMIT" "$cache/easybuild-easyblocks-v5.4.1"

framework=$(ensure_mirror "$FRAMEWORK_URL" easybuild-framework)
git -C "$framework" fetch origin "refs/tags/${FRAMEWORK_TAG}:refs/tags/${FRAMEWORK_TAG}"
test "$(git -C "$framework" rev-parse "${FRAMEWORK_TAG}^{commit}")" = "$FRAMEWORK_TAG_COMMIT"
checkout "$framework" "$FRAMEWORK_TAG_COMMIT" "$cache/easybuild-framework-v5.4.1"

cat >"$cache/env.sh" <<EOF
# Generated by scripts/fetch-upstream-trees.sh. Source this file.
export EB_EASYCONFIGS_DEVELOP="$cache/easybuild-easyconfigs-develop"
export EB_EASYCONFIGS_541="$cache/easybuild-easyconfigs-v5.4.1"
export EB_EASYCONFIGS="$cache/easybuild-easyconfigs-develop/easybuild/easyconfigs"
export EB_EASYBLOCKS="$cache/easybuild-easyblocks-v5.4.1"
export EB_EASYBUILD_FRAMEWORK="$cache/easybuild-framework-v5.4.1"
EOF

echo "source $cache/env.sh"
