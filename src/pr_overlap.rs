//! Which open pull requests to a software layer would build the same modules.
//!
//! A software-layer pull request adds lines to an easystack, and what it really
//! asks for is everything `eb --easystack <file> --robot` would install for
//! those lines on the current stack: the named easyconfigs plus every
//! dependency not installed yet. Two pull requests that both need a module
//! nobody has built will both build it, and the reviewer who has to order
//! them works that out by hand today.
//!
//! This module answers it from the recipes alone, with no build and no
//! model. Per pull request it reads the easystack entries the change adds,
//! finds their easyconfigs on the robot path (the release tree plus, for an
//! entry pinned with `from-commit`, the easyconfigs tree at that commit ahead
//! of it), and closes
//! them with [`crate::build_order::closure_against_installed`] against the list
//! of installed modules. An installed module is a leaf, as it is for the robot.
//! The overlap report is then a set intersection over the to-build sets.
//!
//! The pull request's files are read as data. Nothing from a pull request is
//! executed, which is what lets a scheduled job on the base repository run
//! this over pull requests from forks.

use crate::build_order::{closure_against_installed, module_name, Choice, ModuleKey};
use crate::domain::Candidate;
use crate::easystack::{parse_easystack_entries, EasystackEntry};
use crate::eb_parse::merge_candidates_with_precedence;
use serde::{Deserialize, Serialize};
use std::collections::{BTreeMap, BTreeSet};

/// Schema of the per-PR record and the index. Bumped on any breaking change.
pub const PR_OVERLAP_SCHEMA_VERSION: u32 = 1;

/// Header written at the top of every generated file.
pub const GENERATED_HEADER: &str = "# Generated by `eb-stack pr-overlap`. Data only: the branch holding this file is\n# regenerated on every run and must never be merged.\n";

/// One changed easystack file in a pull request.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct EasystackChange {
    /// Path in the repository, e.g.
    /// `easystacks/software.eessi.io/2026.06/eessi-2026.06-eb-5.4.0-2026.1.yml`.
    pub path: String,
    /// File text on the base branch; absent for a file the PR adds.
    #[serde(default)]
    pub base: Option<String>,
    /// File text at the PR head; absent for a file the PR deletes.
    #[serde(default)]
    pub head: Option<String>,
}

/// One pull request as read from the forge: identity plus easystack changes.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct PrInput {
    /// Pull request number.
    pub number: u64,
    /// Head commit the files were read at.
    pub head_sha: String,
    /// Title, for the report.
    #[serde(default)]
    pub title: Option<String>,
    /// Changed easystack files. Other changed files are not needed.
    #[serde(default)]
    pub easystacks: Vec<EasystackChange>,
}

/// Settings shared by every record of one run.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct OverlapConfig {
    /// Stack version whose easystacks count, e.g. `2026.06`.
    pub eessi_version: String,
    /// Where the installed list came from, e.g. `x86_64/amd/zen4`.
    pub installed_source: String,
    /// Easystack paths containing any of these substrings are left out
    /// (accelerator or arch-specific stacks the installed list does not cover).
    pub exclude_paths: Vec<String>,
    /// When non-empty, only easystack paths containing one of these substrings
    /// are kept. Used to run a second pass over an arch the first pass excluded.
    pub include_paths: Vec<String>,
    /// RFC 3339 timestamp written into every record.
    pub generated_at: String,
}

/// One easystack entry a pull request adds.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct RecordEntry {
    /// Easystack file the entry is in.
    pub easystack: String,
    /// Easyconfig file name.
    pub easyconfig: String,
    /// `from-commit` pin, when the entry has one.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub from_commit: Option<String>,
    /// EasyBuild version from the easystack's file name, when it carries one.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub eb_version: Option<String>,
}

/// What one pull request would build, as stored on the data branch.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct PrRecord {
    /// Record schema.
    pub schema_version: u32,
    /// Pull request number.
    pub pr: u64,
    /// Head commit the record was computed for.
    pub head_sha: String,
    /// Title at that commit.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub title: Option<String>,
    /// When the record was computed.
    pub generated_at: String,
    /// Stack version.
    pub eessi_version: String,
    /// Where the installed list came from.
    pub installed_source: String,
    /// Easystack files the pull request changes for that version.
    pub easystack_files: Vec<String>,
    /// Module names that would be built, sorted.
    pub to_build: Vec<String>,
    /// Installed modules the closure reached and stopped at, sorted.
    pub already_installed: Vec<String>,
    /// Requirements no easyconfig on the robot path satisfies.
    pub unresolved: Vec<String>,
    /// The easystack entries the pull request adds.
    pub entries: Vec<RecordEntry>,
}

/// Robot-path trees: the release tree, and per `from-commit` the easyconfigs
/// tree at that commit, which EasyBuild puts ahead of the release tree.
#[derive(Debug, Clone, Default)]
pub struct RobotTrees {
    /// Easyconfigs of the EasyBuild release the stack uses.
    pub base: Vec<Candidate>,
    /// Easyconfigs fetched for one `from-commit`, keyed by commit.
    pub commits: BTreeMap<String, Vec<Candidate>>,
}

/// Stack version from an easystack path under `easystacks/software.eessi.io/`.
pub fn eessi_version_of(path: &str) -> Option<String> {
    let marker = "software.eessi.io/";
    let rest = &path[path.find(marker)? + marker.len()..];
    let version = rest.split('/').next()?;
    if version.is_empty() || !version.chars().all(|c| c.is_ascii_digit() || c == '.') {
        return None;
    }
    Some(version.to_string())
}

/// EasyBuild version from an easystack file name such as
/// `eessi-2026.06-eb-5.4.0-2026.1.yml`.
pub fn eb_version_of(path: &str) -> Option<String> {
    let name = path.rsplit('/').next()?;
    let at = name.find("-eb-")? + 4;
    let version: String = name[at..]
        .chars()
        .take_while(|c| c.is_ascii_digit() || *c == '.')
        .collect();
    let version = version.trim_end_matches('.').to_string();
    (!version.is_empty()).then_some(version)
}

/// Entries present at head and not on base, in head order.
pub fn added_entries(change: &EasystackChange) -> Vec<EasystackEntry> {
    let parse = |text: &Option<String>| {
        text.as_deref()
            .map(|t| parse_easystack_entries(t).unwrap_or_default())
            .unwrap_or_default()
    };
    let base = parse(&change.base);
    parse(&change.head)
        .into_iter()
        .filter(|e| !base.contains(e))
        .collect()
}

/// Read an installed-module list: one `Name/VersionFull` per line, as listed
/// under an install tree's `software/` or `modules/all/`. Blank lines and `#`
/// comments are skipped; a trailing `.lua` and a trailing `/` are dropped.
pub fn parse_installed(text: &str) -> BTreeSet<String> {
    text.lines()
        .map(str::trim)
        .filter(|l| !l.is_empty() && !l.starts_with('#'))
        .map(|l| {
            let l = l.trim_end_matches('/');
            l.strip_suffix(".lua").unwrap_or(l).to_string()
        })
        .collect()
}

fn find_start<'a>(universe: &'a [Candidate], file: &str) -> Option<&'a Candidate> {
    universe
        .iter()
        .find(|c| c.easyconfig_path.rsplit('/').next() == Some(file))
}

/// The record for one pull request, or `None` when it changes no easystack of
/// the configured version.
pub fn pr_record(
    pr: &PrInput,
    trees: &RobotTrees,
    installed: &BTreeSet<String>,
    config: &OverlapConfig,
) -> Option<PrRecord> {
    let mut files = Vec::new();
    // Entries grouped by (from-commit, rebuild), since each group has its own
    // robot path and its own notion of what counts as installed.
    let mut groups: BTreeMap<(Option<String>, bool), Vec<String>> = BTreeMap::new();
    let mut entries = Vec::new();
    for change in &pr.easystacks {
        if eessi_version_of(&change.path).as_deref() != Some(config.eessi_version.as_str()) {
            continue;
        }
        if config
            .exclude_paths
            .iter()
            .any(|s| !s.is_empty() && change.path.contains(s.as_str()))
        {
            continue;
        }
        if !config.include_paths.is_empty()
            && !config
                .include_paths
                .iter()
                .any(|s| !s.is_empty() && change.path.contains(s.as_str()))
        {
            continue;
        }
        let added = added_entries(change);
        if added.is_empty() {
            continue;
        }
        files.push(change.path.clone());
        let rebuild = change.path.contains("/rebuilds/");
        for entry in added {
            groups
                .entry((entry.from_commit.clone(), rebuild))
                .or_default()
                .push(entry.file.clone());
            entries.push(RecordEntry {
                easystack: change.path.clone(),
                easyconfig: entry.file,
                from_commit: entry.from_commit,
                eb_version: eb_version_of(&change.path),
            });
        }
    }
    if entries.is_empty() {
        return None;
    }

    let mut to_build = BTreeSet::new();
    let mut already = BTreeSet::new();
    let mut unresolved = BTreeSet::new();
    for ((commit, rebuild), group_files) in &groups {
        let merged;
        let universe: &[Candidate] = match commit.as_ref().and_then(|c| trees.commits.get(c)) {
            Some(overlay) => {
                merged = merge_candidates_with_precedence(&[trees.base.clone(), overlay.clone()]);
                &merged
            }
            None => {
                if let Some(c) = commit {
                    unresolved.insert(format!(
                        "from-commit {c}: no easyconfigs given for this commit, release tree used"
                    ));
                }
                &trees.base
            }
        };
        let mut starts = Vec::new();
        for file in group_files {
            match find_start(universe, file) {
                Some(c) => starts.push(ModuleKey::of(c)),
                None => {
                    unresolved.insert(format!("{file}: no such easyconfig on the robot path"));
                }
            }
        }
        let forced: BTreeSet<ModuleKey> = if *rebuild {
            starts.iter().cloned().collect()
        } else {
            BTreeSet::new()
        };
        let is_installed =
            |k: &ModuleKey| !forced.contains(k) && installed.contains(&module_name(k));
        let closure = closure_against_installed(universe, &starts, Choice::Newest, &is_installed);
        to_build.extend(closure.to_build.iter().map(module_name));
        already.extend(closure.installed.iter().map(module_name));
        for u in closure.unresolved {
            unresolved.insert(format!("{} needs {}", module_name(&u.from), u.requirement));
        }
    }

    Some(PrRecord {
        schema_version: PR_OVERLAP_SCHEMA_VERSION,
        pr: pr.number,
        head_sha: pr.head_sha.clone(),
        title: pr.title.clone(),
        generated_at: config.generated_at.clone(),
        eessi_version: config.eessi_version.clone(),
        installed_source: config.installed_source.clone(),
        easystack_files: files,
        to_build: to_build.into_iter().collect(),
        already_installed: already.into_iter().collect(),
        unresolved: unresolved.into_iter().collect(),
        entries,
    })
}

/// Shared to-build modules across records.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct OverlapIndex {
    /// Index schema.
    pub schema_version: u32,
    /// When it was computed.
    pub generated_at: String,
    /// Stack version.
    pub eessi_version: String,
    /// Where the installed list came from.
    pub installed_source: String,
    /// Pull requests with a record, ascending.
    pub prs: Vec<u64>,
    /// Module to the pull requests that would build it, for modules more than
    /// one would build.
    pub shared: BTreeMap<String, Vec<u64>>,
    /// Per pull request: the other pull requests it shares modules with, and
    /// which modules, keyed by the pull request number as a string.
    pub pairs: BTreeMap<String, BTreeMap<String, Vec<String>>>,
}

/// Intersect the to-build sets of every record.
pub fn overlap_index(records: &[PrRecord], config: &OverlapConfig) -> OverlapIndex {
    let mut by_module: BTreeMap<String, BTreeSet<u64>> = BTreeMap::new();
    for r in records {
        for m in &r.to_build {
            by_module.entry(m.clone()).or_default().insert(r.pr);
        }
    }
    let shared: BTreeMap<String, Vec<u64>> = by_module
        .into_iter()
        .filter(|(_, prs)| prs.len() > 1)
        .map(|(m, prs)| (m, prs.into_iter().collect()))
        .collect();
    let mut pairs: BTreeMap<u64, BTreeMap<u64, Vec<String>>> = BTreeMap::new();
    for (module, prs) in &shared {
        for a in prs {
            for b in prs {
                if a != b {
                    pairs
                        .entry(*a)
                        .or_default()
                        .entry(*b)
                        .or_default()
                        .push(module.clone());
                }
            }
        }
    }
    let mut prs: Vec<u64> = records.iter().map(|r| r.pr).collect();
    prs.sort_unstable();
    prs.dedup();
    OverlapIndex {
        schema_version: PR_OVERLAP_SCHEMA_VERSION,
        generated_at: config.generated_at.clone(),
        eessi_version: config.eessi_version.clone(),
        installed_source: config.installed_source.clone(),
        prs,
        shared,
        pairs: pairs
            .into_iter()
            .map(|(a, m)| {
                (
                    a.to_string(),
                    m.into_iter().map(|(b, v)| (b.to_string(), v)).collect(),
                )
            })
            .collect(),
    }
}

/// A record or index as TOML, with the generated-file header.
pub fn to_toml<T: Serialize>(value: &T) -> Result<String, toml::ser::Error> {
    Ok(format!("{GENERATED_HEADER}\n{}", toml::to_string(value)?))
}

/// One pull request's record, with `to_build` as one sorted line per module.
///
/// The same line in two `prs/<N>.toml` files is a module both pull requests
/// would build. `git diff` shows a deploy dropping that line, and
/// `sort | uniq -d` across the `to_build` lines is the overlap.
pub fn record_to_toml(record: &PrRecord) -> Result<String, toml::ser::Error> {
    let mut modules = record.to_build.clone();
    modules.sort();
    let mut without = record.clone();
    without.to_build.clear();
    let body = expand_to_build(&toml::to_string(&without)?, &modules);
    Ok(format!("{GENERATED_HEADER}\n{body}"))
}

/// Replace the empty `to_build` array left by [`record_to_toml`] with one
/// quoted module per line. Any other empty array is left alone.
fn expand_to_build(text: &str, modules: &[String]) -> String {
    let mut out = String::with_capacity(text.len() + modules.len() * 48);
    let mut replaced = false;
    for line in text.lines() {
        if !replaced && line == "to_build = []" {
            replaced = true;
            out.push_str(&render_to_build(modules));
            continue;
        }
        out.push_str(line);
        out.push('\n');
    }
    if !replaced {
        out.push_str(&render_to_build(modules));
    }
    out
}

fn render_to_build(modules: &[String]) -> String {
    if modules.is_empty() {
        return "to_build = []\n".to_string();
    }
    let mut out = String::from("to_build = [\n");
    for module in modules {
        out.push_str("  \"");
        out.push_str(&module.replace('\\', "\\\\").replace('"', "\\\""));
        out.push_str("\",\n");
    }
    out.push_str("]\n");
    out
}

/// The overlap report for reviewers, as Markdown.
///
/// Pull requests are written as plain `#N` text inside a file, which links on
/// GitHub without adding anything to the pull requests' timelines.
pub fn render_markdown(records: &[PrRecord], index: &OverlapIndex, repo_url: &str) -> String {
    let link = |n: u64| {
        if repo_url.is_empty() {
            format!("#{n}")
        } else {
            format!("[#{n}]({}/pull/{n})", repo_url.trim_end_matches('/'))
        }
    };
    let mut out = String::new();
    out.push_str("<!-- Generated by `eb-stack pr-overlap`. This branch is never merged. -->\n");
    out.push_str(&format!(
        "# Shared builds between open pull requests ({})\n\n",
        index.eessi_version
    ));
    out.push_str(&format!(
        "Computed {} against the modules installed for `{}`. {} pull requests change an easystack for this version.\n\n",
        index.generated_at,
        index.installed_source,
        records.len()
    ));
    out.push_str("## Modules more than one pull request would build\n\n");
    if index.shared.is_empty() {
        out.push_str("None.\n\n");
    } else {
        out.push_str("| Module | Pull requests |\n|---|---|\n");
        for (module, prs) in &index.shared {
            let prs: Vec<String> = prs.iter().map(|n| link(*n)).collect();
            out.push_str(&format!("| `{module}` | {} |\n", prs.join(", ")));
        }
        out.push('\n');
    }
    out.push_str("## Per pull request\n\n");
    let mut sorted: Vec<&PrRecord> = records.iter().collect();
    sorted.sort_by_key(|r| r.pr);
    for r in sorted {
        let short: String = r.head_sha.chars().take(10).collect();
        out.push_str(&format!(
            "### {} {} (`{short}`)\n\n",
            link(r.pr),
            r.title.as_deref().unwrap_or("")
        ));
        out.push_str(&format!(
            "Builds {} modules; {} reached modules are already installed.\n\n",
            r.to_build.len(),
            r.already_installed.len()
        ));
        if let Some(others) = index.pairs.get(&r.pr.to_string()) {
            for (other, modules) in others {
                let n: u64 = other.parse().unwrap_or_default();
                let list: Vec<String> = modules.iter().map(|m| format!("`{m}`")).collect();
                out.push_str(&format!(
                    "- shares {} with {}: {}\n",
                    modules.len(),
                    link(n),
                    list.join(", ")
                ));
            }
        } else {
            out.push_str("- shares nothing with another open pull request\n");
        }
        for u in &r.unresolved {
            out.push_str(&format!("- unresolved: {u}\n"));
        }
        out.push_str("\n<details><summary>To build</summary>\n\n");
        for m in &r.to_build {
            out.push_str(&format!("- `{m}`\n"));
        }
        out.push_str("\n</details>\n\n");
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn versions_come_from_the_easystack_path() {
        let p = "easystacks/software.eessi.io/2026.06/eessi-2026.06-eb-5.4.0-2026.1.yml";
        assert_eq!(eessi_version_of(p).as_deref(), Some("2026.06"));
        assert_eq!(eb_version_of(p).as_deref(), Some("5.4.0"));
        assert_eq!(
            eb_version_of(
                "easystacks/software.eessi.io/2026.06/eessi-2026.06-eb-5.3.1-001-system.yml"
            )
            .as_deref(),
            Some("5.3.1")
        );
        assert_eq!(eessi_version_of("README.md"), None);
    }

    #[test]
    fn only_lines_the_head_adds_count() {
        let change = EasystackChange {
            path: "x.yml".into(),
            base: Some("easyconfigs:\n  - A-1.eb\n".into()),
            head: Some(
                "easyconfigs:\n  - A-1.eb\n  - B-2.eb:\n      options:\n        from-commit: abc\n"
                    .into(),
            ),
        };
        let added = added_entries(&change);
        assert_eq!(added.len(), 1);
        assert_eq!(added[0].file, "B-2.eb");
        assert_eq!(added[0].from_commit.as_deref(), Some("abc"));
    }

    #[test]
    fn to_build_is_one_sorted_line_per_module() {
        let record = PrRecord {
            schema_version: 1,
            pr: 1,
            head_sha: "abc".into(),
            title: None,
            generated_at: "2026-10-19T12:00:00Z".into(),
            eessi_version: "2026.06".into(),
            installed_source: "x86_64/amd/zen4".into(),
            easystack_files: Vec::new(),
            to_build: vec!["b/2".into(), "a/1".into()],
            already_installed: Vec::new(),
            unresolved: Vec::new(),
            entries: Vec::new(),
        };
        let text = record_to_toml(&record).expect("toml");
        let a = text.find("  \"a/1\",\n").expect("a on its own line");
        let b = text.find("  \"b/2\",\n").expect("b on its own line");
        assert!(a < b, "sorted, got {text}");
        let back: PrRecord = toml::from_str(&text).expect("parse");
        assert_eq!(back.to_build, vec!["a/1".to_string(), "b/2".to_string()]);
        assert_eq!(back.pr, 1);
    }

    #[test]
    fn installed_lists_accept_module_and_directory_spellings() {
        let set = parse_installed("# zen4\nzlib/1.3.1-GCCcore-15.2.0.lua\nGCCcore/15.2.0/\n\n");
        assert!(set.contains("zlib/1.3.1-GCCcore-15.2.0"));
        assert!(set.contains("GCCcore/15.2.0"));
        assert_eq!(set.len(), 2);
    }
}
