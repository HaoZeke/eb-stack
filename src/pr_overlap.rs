    #[test]
    fn easyconfig_rows_cover_each_overlap_kind() {
        let records = vec![
            ec_row(
                1,
                vec![changed("l/Lib.eb", "modified", Some("Lib/1.0"))],
                &["Lib/1.0"],
                &[],
            ),
            ec_row(
                2,
                vec![changed("l/Lib.eb", "modified", Some("Lib/1.0"))],
                &["Lib/1.0"],
                &[],
            ),
            ec_row(
                3,
                vec![changed("n/New.eb", "added", Some("New/1.0"))],
                &["New/1.0"],
                &["New/1.0"],
            ),
            ec_row(
                4,
                vec![changed("n/New.eb", "added", Some("New/1.0"))],
                &["New/1.0"],
                &["New/1.0"],
            ),
            ec_row(
                5,
                vec![changed("d/Dep.eb", "added", Some("Dep/1.0"))],
                &["Dep/1.0"],
                &["Dep/1.0"],
            ),
            ec_row(
                6,
                vec![changed("u/User.eb", "added", Some("User/1.0"))],
                &["Dep/1.0", "User/1.0"],
                &["User/1.0"],
            ),
        ];
        let index = overlap_index(&records, &ec_config());
        assert_eq!(index.schema_version, 2);
        let kinds: Vec<&str> = index.rows.iter().map(|row| row.kind.as_str()).collect();
        assert!(kinds.contains(&"same-file"), "{kinds:?}");
        assert!(kinds.contains(&"same-module"), "{kinds:?}");
        assert!(kinds.contains(&"shared-new-module"), "{kinds:?}");
        assert!(kinds.contains(&"depends-on"), "{kinds:?}");
        let same_file = index
            .rows
            .iter()
            .find(|row| row.kind == "same-file")
            .unwrap();
        assert_eq!(same_file.path, "l/Lib.eb");
        assert_eq!(same_file.prs, vec![1, 2]);
        let same_module = index
            .rows
            .iter()
            .find(|row| row.kind == "same-module")
            .unwrap();
        assert_eq!(same_module.module, "New/1.0");
        assert_eq!(same_module.prs, vec![3, 4]);
        let shared = index
            .rows
            .iter()
            .find(|row| row.kind == "shared-new-module" && row.module == "New/1.0")
            .unwrap();
        assert_eq!(shared.prs, vec![3, 4]);
        let depends = index
            .rows
            .iter()
            .find(|row| row.kind == "depends-on")
            .unwrap();
        assert_eq!(depends.from, Some(5));
        assert_eq!(depends.to, Some(6));
        assert_eq!(depends.modules, vec!["Dep/1.0".to_string()]);
        let md = render_markdown(&records, &index, "");
        assert!(md.contains("## same-file\n\n| Path |"));
        assert!(md.contains("## depends-on\n\n| From | To | Modules |"));
        assert!(md.contains("| #5 | #6 | `Dep/1.0` |"));
        assert!(!md.contains("Shared builds between open pull requests"));
    }

