use serde::{Deserialize, Serialize};
use std::collections::{BTreeMap, BTreeSet};

/// Schema of an easyconfigs pull-request record. A software-layer record stays
/// at [`PR_OVERLAP_SCHEMA_VERSION`] so an existing file is unchanged.
pub const EASYCONFIG_PR_SCHEMA_VERSION: u32 = 2;

/// Schema of the per-PR record and the index. Bumped on any breaking change.
pub const PR_OVERLAP_SCHEMA_VERSION: u32 = 1;

/// Header written at the top of every generated file.
pub const GENERATED_HEADER: &str = "# Generated by `eb-stack pr-overlap`. Data only: the branch holding this file is\n# regenerated on every run and must never be merged.\n";

/// One changed file in a pull request: path plus the text on each side.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct FileChange {
    /// Path in the repository.
    pub path: String,
    /// File text on the base branch; absent for a file the PR adds.
    #[serde(default)]
    pub base: Option<String>,
    /// File text at the PR head; absent for a file the PR deletes.
    #[serde(default)]
    pub head: Option<String>,
    /// Git blob id of `base`, when the fetch recorded it.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub base_blob: Option<String>,
    /// Git blob id of `head`, when the fetch recorded it.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub head_blob: Option<String>,
}

/// One changed file stored on a record: path, kind, and base/head text or blob.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct FileRevision {
    /// Path in the software-layer repository, or an easyconfig filename.
    pub path: String,
    /// `easystack` or `easyconfig`.
    pub kind: String,
    /// Git blob id of the base text.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub base_blob: Option<String>,
    /// Git blob id of the head text.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub head_blob: Option<String>,
    /// Base text. Absent when the fetch stored only a blob id.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub base: Option<String>,
    /// Head text. Absent when the fetch stored only a blob id.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub head: Option<String>,
}

/// One changed easystack file. Same fields and serde shape as [`FileChange`].
pub type EasystackChange = FileChange;

/// One pull request as read from the forge: identity plus easystack changes.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct PrInput {
    /// Pull request number.
    pub number: u64,
    /// Head commit the files were read at.
    pub head_sha: String,
    /// Title, for the report.
    #[serde(default)]
    pub title: Option<String>,
    /// Changed easystack files.
    #[serde(default)]
    pub easystacks: Vec<EasystackChange>,
    /// Changed easyconfig files (`*.eb`), with base and head text or blob ids.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub files: Vec<FileRevision>,
    /// Changed easyconfig files (`path` ending in `.eb`) to close over the
    /// base tree. Other paths are ignored and named in the record's notes.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub easyconfigs: Vec<FileChange>,
}

/// Settings shared by every record of one run.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct OverlapConfig {
    /// Stack version whose easystacks count, e.g. `2026.06`.
    pub eessi_version: String,
    /// Where the installed list came from, e.g. `x86_64/amd/zen4`.
    pub installed_source: String,
    /// Easystack paths containing any of these substrings are left out
    /// (accelerator or arch-specific stacks the installed list does not cover).
    pub exclude_paths: Vec<String>,
    /// When non-empty, only easystack paths containing one of these substrings
    /// are kept. Used to run a second pass over an arch the first pass excluded.
    pub include_paths: Vec<String>,
    /// RFC 3339 timestamp written into every record.
    pub generated_at: String,
    /// Dependencies dropped the way EasyBuild's `--filter-deps` drops them,
    /// together with everything reachable only through them.
    pub filter_deps: FilterDeps,
    /// Easyblock classes to resolve. `None` skips the check.
    pub easyblocks: Option<EasyblockCatalog>,
}

/// Easyblock classes a run can see.
///
/// `base` is the installed easyblocks package. `commits` holds the classes
/// from each `include-easyblocks-from-commit` tree that was passed in.
/// A class in a commit tree is what `--include-easyblocks-from-commit` adds
/// ahead of the installed package. `check` is set only when that installed
/// package was passed in: without it, every derived class would look missing.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct EasyblockCatalog {
    /// When true, a class in neither `base` nor the entry's commit trees is
    /// `easyblock <class> missing` and is not counted as a module to build.
    pub check: bool,
    /// Class name to the file that defines it in the installed package.
    pub base: BTreeMap<String, String>,
    /// Per commit: class name to the file that defines it.
    pub commits: BTreeMap<String, BTreeMap<String, String>>,
}

/// One easystack entry a pull request adds.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct RecordEntry {
    /// Easystack file the entry is in.
    pub easystack: String,
    /// Easyconfig file name.
    pub easyconfig: String,
    /// `from-commit` pin, when the entry has one.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub from_commit: Option<String>,
    /// EasyBuild version from the easystack's file name, when it carries one.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub eb_version: Option<String>,
}

/// A base-tree module that resolves a dependency to a file this pull request
/// modifies or deletes. `depth` 1 is direct.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord, Serialize, Deserialize)]
pub struct ReverseDependent {
    /// Module name, `name/version[-toolchain]versionsuffix`.
    pub module: String,
    /// Shortest dependency distance from a changed file.
    pub depth: u32,
}

/// One easyconfig a pull request adds, changes, or deletes.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ChangedEasyconfig {
    /// Path in the repository.
    pub path: String,
    /// `added`, `modified`, or `deleted`.
    pub status: String,
    /// Module the file provides. Absent when the text did not parse.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub module: Option<String>,
}

/// What one pull request would build, as stored on the data branch.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct PrRecord {
    /// Record schema.
    pub schema_version: u32,
    /// Pull request number.
    pub pr: u64,
    /// Head commit the record was computed for.
    pub head_sha: String,
    /// Title at that commit.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub title: Option<String>,
    /// When the record was computed.
    pub generated_at: String,
    /// Stack version. Empty, and omitted, for an easyconfigs pull request.
    #[serde(default, skip_serializing_if = "String::is_empty")]
    pub eessi_version: String,
    /// Where the installed list came from.
    pub installed_source: String,
    /// Easystack files the pull request changes for that version.
    pub easystack_files: Vec<String>,
    /// Module names that would be built, sorted.
    pub to_build: Vec<String>,
    /// Installed modules the closure reached and stopped at, sorted.
    pub already_installed: Vec<String>,
    /// Requirements no easyconfig on the robot path satisfies, and easyblock
    /// classes the run cannot resolve (`easyblock EB_eOn missing`).
    pub unresolved: Vec<String>,
    /// Easyblocks supplied by a commit or pull request, and commits named by
    /// an entry whose tree was not passed in.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub notes: Vec<String>,
    /// The easystack entries the pull request adds.
    pub entries: Vec<RecordEntry>,
    /// Easystack and easyconfig files this pull request changes. Base and head
    /// text, or their blob ids, are what a later merge-order uses to see a
    /// hunk collision without the original JSON.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub revisions: Vec<FileRevision>,
    /// `software-layer` or `easyconfigs`. Empty on a software-layer record,
    /// which keeps the schema 1 field set.
    #[serde(default, skip_serializing_if = "String::is_empty")]
    pub kind: String,
    /// Easyconfigs this pull request adds, changes, or deletes.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub changed_easyconfigs: Vec<ChangedEasyconfig>,
    /// Every module the changed easyconfigs reach, sorted, including the
    /// pull request's own modules.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub closure: Vec<String>,
    /// Closure modules the base tree alone does not provide, sorted.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub new_modules: Vec<String>,
    /// Base-tree modules that depend on a file this pull request modifies
    /// or deletes, nearest first.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub reverse_dependents: Vec<ReverseDependent>,
}

/// Robot-path trees: the release tree, and per `from-commit` the easyconfigs
/// tree at that commit, which EasyBuild puts ahead of the release tree.
#[derive(Debug, Clone, Default)]
pub struct RobotTrees {
    /// Easyconfigs of the EasyBuild release the stack uses.
    pub base: Vec<Candidate>,
    /// Easyconfigs fetched for one `from-commit`, keyed by commit.
    pub commits: BTreeMap<String, Vec<Candidate>>,
}

/// Stack version from an easystack path under `easystacks/software.eessi.io/`.
pub fn eessi_version_of(path: &str) -> Option<String> {
    let marker = "software.eessi.io/";
    let rest = &path[path.find(marker)? + marker.len()..];
    let version = rest.split('/').next()?;
    if version.is_empty() || !version.chars().all(|c| c.is_ascii_digit() || c == '.') {
        return None;
    }
    Some(version.to_string())
}

/// EasyBuild version from an easystack file name such as
/// `eessi-2026.06-eb-5.4.0-2026.1.yml`.
pub fn eb_version_of(path: &str) -> Option<String> {
    let name = path.rsplit('/').next()?;
    let at = name.find("-eb-")? + 4;
    let version: String = name[at..]
        .chars()
        .take_while(|c| c.is_ascii_digit() || *c == '.')
        .collect();
    let version = version.trim_end_matches('.').to_string();
    (!version.is_empty()).then_some(version)
}

/// Entries present at head and not on base, in head order.
pub fn added_entries(change: &EasystackChange) -> Vec<EasystackEntry> {
    let parse = |text: &Option<String>| {
        text.as_deref()
            .map(|t| parse_easystack_entries(t).unwrap_or_default())
            .unwrap_or_default()
    };
    let base = parse(&change.base);
    parse(&change.head)
        .into_iter()
        .filter(|e| !base.contains(e))
        .collect()
}

/// Read an installed-module list: one `Name/VersionFull` per line, as listed
/// under an install tree's `software/` or `modules/all/`. Blank lines and `#`
/// comments are skipped; a trailing `.lua` and a trailing `/` are dropped.
pub fn parse_installed(text: &str) -> BTreeSet<String> {
    text.lines()
        .map(str::trim)
        .filter(|l| !l.is_empty() && !l.starts_with('#'))
        .map(|l| {
            let l = l.trim_end_matches('/');
            l.strip_suffix(".lua").unwrap_or(l).to_string()
        })
        .collect()
}

fn find_start<'a>(universe: &'a [Candidate], file: &str) -> Option<&'a Candidate> {
    universe
        .iter()
        .find(|c| c.easyconfig_path.rsplit('/').next() == Some(file))
}

fn stack_kept(path: &str, config: &OverlapConfig) -> bool {
    if eessi_version_of(path).as_deref() != Some(config.eessi_version.as_str()) {
        return false;
    }
    if config
        .exclude_paths
        .iter()
        .any(|s| !s.is_empty() && path.contains(s.as_str()))
    {
        return false;
    }
    config.include_paths.is_empty()
        || config
            .include_paths
            .iter()
            .any(|s| !s.is_empty() && path.contains(s.as_str()))
}

/// Easystack revisions for this stack version, then easyconfig files.
///
/// Conflict detection reads these later, so the text or blob has to be here
/// even when the closure itself is already stored.
pub fn file_revisions(pr: &PrInput, config: &OverlapConfig) -> Vec<FileRevision> {
    let mut out: Vec<FileRevision> = pr
        .easystacks
        .iter()
        .filter(|change| stack_kept(&change.path, config))
        .map(|change| FileRevision {
            path: change.path.clone(),
            kind: "easystack".into(),
            base_blob: change.base_blob.clone(),
            head_blob: change.head_blob.clone(),
            base: change.base.clone(),
            head: change.head.clone(),
        })
        .collect();
    out.extend(
        pr.files
            .iter()
            .filter(|file| file.kind == "easyconfig")
            .cloned(),
    );
    out
}

/// The record for one pull request, or `None` when it changes no easystack of
/// the configured version.
pub fn pr_record(
    pr: &PrInput,
    trees: &RobotTrees,
    installed: &BTreeSet<String>,
    config: &OverlapConfig,
) -> Option<PrRecord> {
    let mut files = Vec::new();
    // Entries grouped by (from-commit, rebuild), since each group has its own
    // robot path and its own notion of what counts as installed.
    let mut groups: BTreeMap<(Option<String>, bool), Vec<Start>> = BTreeMap::new();
    let mut entries = Vec::new();
    let revisions = file_revisions(pr, config);
    for change in &pr.easystacks {
        if !stack_kept(&change.path, config) {
            continue;
        }
        let added = added_entries(change);
        if added.is_empty() {
            continue;
        }
        files.push(change.path.clone());
        let rebuild = change.path.contains("/rebuilds/");
        for entry in added {
            groups
                .entry((entry.from_commit.clone(), rebuild))
                .or_default()
                .push(Start {
                    file: entry.file.clone(),
                    easyblock_commit: entry.include_easyblocks_from_commit.clone(),
                    easyblock_pr: entry.include_easyblocks_from_pr.clone(),
                });
            entries.push(RecordEntry {
                easystack: change.path.clone(),
                easyconfig: entry.file,
                from_commit: entry.from_commit,
                eb_version: eb_version_of(&change.path),
            });
        }
    }
    if entries.is_empty() {
        return None;
    }

    let mut to_build = BTreeSet::new();
    let mut already = BTreeSet::new();
    let mut unresolved = BTreeSet::new();
    let mut notes = BTreeSet::new();
    for ((commit, rebuild), group) in &groups {
        let merged;
        let raw: &[Candidate] = match commit.as_ref().and_then(|c| trees.commits.get(c)) {
            Some(overlay) => {
                merged = merge_candidates_with_precedence(&[trees.base.clone(), overlay.clone()]);
                &merged
            }
            None => {
                if let Some(c) = commit {
                    notes.insert(format!(
                        "from-commit {c}: no easyconfigs given for this commit, release tree used"
                    ));
                }
                &trees.base
            }
        };
        let mut filtered: Vec<Candidate>;
        let universe: &[Candidate] = if config.filter_deps.is_empty() {
            raw
        } else {
            filtered = raw.to_vec();
            config.filter_deps.apply(&mut filtered);
            &filtered
        };
        let mut starts = Vec::new();
        for start in group {
            match find_start(universe, &start.file) {
                Some(candidate) => starts.push(ModuleKey::of(candidate)),
                None => {
                    unresolved.insert(format!(
                        "{}: no such easyconfig on the robot path",
                        start.file
                    ));
                }
            }
        }
        let forced: BTreeSet<ModuleKey> = if *rebuild {
            starts.iter().cloned().collect()
        } else {
            BTreeSet::new()
        };
        let is_installed =
            |k: &ModuleKey| !forced.contains(k) && installed.contains(&module_name(k));
        let closure = closure_against_installed(universe, &starts, Choice::Newest, &is_installed);
        let easyblock_commits: BTreeSet<String> = group
            .iter()
            .filter_map(|start| start.easyblock_commit.clone())
            .collect();
        let kept = retain_resolved_easyblocks(
            &closure.to_build,
            universe,
            config.easyblocks.as_ref(),
            &easyblock_commits,
            &mut unresolved,
        );
        note_provided_easyblocks(
            group,
            &kept,
            universe,
            config.easyblocks.as_ref(),
            &easyblock_commits,
            &mut notes,
        );
        to_build.extend(kept.into_iter().map(|key| module_name(&key)));
        already.extend(closure.installed.iter().map(module_name));
        for requirement in closure.unresolved {
            unresolved.insert(format!(
                "{} needs {}",
                module_name(&requirement.from),
                requirement.requirement
            ));
        }
    }

    Some(PrRecord {
        schema_version: PR_OVERLAP_SCHEMA_VERSION,
        pr: pr.number,
        head_sha: pr.head_sha.clone(),
        title: pr.title.clone(),
        generated_at: config.generated_at.clone(),
        eessi_version: config.eessi_version.clone(),
        installed_source: config.installed_source.clone(),
        easystack_files: files,
        to_build: to_build.into_iter().collect(),
        already_installed: already.into_iter().collect(),
        unresolved: unresolved.into_iter().collect(),
        notes: notes.into_iter().collect(),
        entries,
        revisions,
        kind: String::new(),
        changed_easyconfigs: Vec::new(),
        closure: Vec::new(),
        new_modules: Vec::new(),
        reverse_dependents: Vec::new(),
    })
}

/// Path key used to match a pull-request path to a parsed easyconfig path.
///
/// Both sides may be a repository path (`easybuild/easyconfigs/g/Foo/Foo-1.0.eb`)
/// or an absolute path under a checkout. The part after `easyconfigs/` is the
/// same key EasyBuild uses for the file.
fn easyconfig_key(path: &str) -> &str {
    path.rsplit_once("easyconfigs/")
        .map(|(_, rest)| rest)
        .unwrap_or_else(|| path.rsplit('/').next().unwrap_or(path))
}

fn paths_match(stored: &str, changed: &str) -> bool {
    let a = easyconfig_key(stored);
    let b = easyconfig_key(changed);
    if a == b {
        return true;
    }
    let nested = |long: &str, short: &str| {
        long.len() > short.len()
            && long.ends_with(short)
            && long.as_bytes().get(long.len() - short.len() - 1) == Some(&b'/')
    };
    nested(a, b) || nested(b, a)
}

fn candidate_from_text(path: &str, text: &str) -> Result<Candidate, String> {
    let mut resolved = crate::eb_parse::resolve_easyconfig_str(text).map_err(|e| e.to_string())?;
    resolved.easyconfig_path = path.to_string();
    Ok(resolved.to_candidate())
}

fn module_of(candidate: &Candidate) -> String {
    module_name(&ModuleKey::of(candidate))
}

struct EasyconfigOverlay {
    tree: Vec<Candidate>,
    changed: Vec<ChangedEasyconfig>,
    notes: BTreeSet<String>,
    unresolved: BTreeSet<String>,
    starts: Vec<ModuleKey>,
}

/// Base tree with this pull request's easyconfig files laid over it.
///
/// Head files are the later layer of [`merge_candidates_with_precedence`], the
/// same precedence a `from-commit` tree has over the release tree. A deleted
/// file is removed. A modified file replaces the base file at that path, so a
/// version change does not leave the old module in the tree.
fn overlay_easyconfigs(base: &[Candidate], changes: &[FileChange]) -> EasyconfigOverlay {
    let mut changed = Vec::new();
    let mut notes = BTreeSet::new();
    let mut unresolved = BTreeSet::new();
    let mut head_layer = Vec::new();
    let mut replaced = Vec::new();
    let mut starts = Vec::new();
    for change in changes {
        if !change.path.ends_with(".eb") {
            notes.insert(format!("ignored {}: not an easyconfig", change.path));
            continue;
        }
        let (status, text) = match (&change.base, &change.head) {
            (None, Some(head)) => ("added", Some(head.as_str())),
            (Some(_), Some(head)) => ("modified", Some(head.as_str())),
            (Some(base_text), None) => ("deleted", Some(base_text.as_str())),
            (None, None) => {
                notes.insert(format!("ignored {}: no base or head text", change.path));
                continue;
            }
        };
        let parsed = text.and_then(|body| match candidate_from_text(&change.path, body) {
            Ok(candidate) => Some(candidate),
            Err(error) => {
                unresolved.insert(format!("{}: {error}", change.path));
                None
            }
        });
        let module = parsed.as_ref().map(module_of);
        if status != "deleted" {
            if let Some(candidate) = parsed {
                starts.push(ModuleKey::of(&candidate));
                head_layer.push(candidate);
            }
        }
        if status != "added" {
            replaced.push(change.path.clone());
        }
        changed.push(ChangedEasyconfig {
            path: change.path.clone(),
            status: status.to_string(),
            module,
        });
    }
    let kept: Vec<Candidate> = base
        .iter()
        .filter(|candidate| {
            !replaced
                .iter()
                .any(|path| paths_match(&candidate.easyconfig_path, path))
        })
        .cloned()
        .collect();
    EasyconfigOverlay {
        tree: merge_candidates_with_precedence(&[kept, head_layer]),
        changed,
        notes,
        unresolved,
        starts,
    }
}

fn direct_dependencies(universe: &[Candidate], candidate: &Candidate) -> Vec<ModuleKey> {
    let start = ModuleKey::of(candidate);
    closure_against_installed(
        universe,
        std::slice::from_ref(&start),
        Choice::Newest,
        &|key| key != &start,
    )
    .installed
}

/// Base-tree modules whose resolved dependency is a modified or deleted file,
/// direct and transitive. Depth 1 depends on the file itself.
fn reverse_dependents(base: &[Candidate], changed: &[ChangedEasyconfig]) -> Vec<ReverseDependent> {
    let targets: BTreeSet<ModuleKey> = base
        .iter()
        .filter(|candidate| {
            changed.iter().any(|change| {
                matches!(change.status.as_str(), "modified" | "deleted")
                    && paths_match(&candidate.easyconfig_path, &change.path)
            })
        })
        .map(ModuleKey::of)
        .collect();
    if targets.is_empty() {
        return Vec::new();
    }
    let mut reverse: BTreeMap<ModuleKey, BTreeSet<ModuleKey>> = BTreeMap::new();
    let mut names: BTreeMap<ModuleKey, String> = BTreeMap::new();
    for candidate in base {
        let key = ModuleKey::of(candidate);
        names.insert(key.clone(), module_name(&key));
        for dep in direct_dependencies(base, candidate) {
            reverse.entry(dep).or_default().insert(key.clone());
        }
    }
    let mut depth_of: BTreeMap<ModuleKey, u32> = BTreeMap::new();
    let mut queue: Vec<(ModuleKey, u32)> = targets.iter().cloned().map(|key| (key, 0)).collect();
    let mut head = 0;
    while head < queue.len() {
        let (key, depth) = queue[head].clone();
        head += 1;
        let Some(dependents) = reverse.get(&key) else {
            continue;
        };
        for dependent in dependents {
            if targets.contains(dependent) || depth_of.contains_key(dependent) {
                continue;
            }
            let next = depth + 1;
            depth_of.insert(dependent.clone(), next);
            queue.push((dependent.clone(), next));
        }
    }
    let mut out: Vec<ReverseDependent> = depth_of
        .into_iter()
        .map(|(key, depth)| ReverseDependent {
            module: names
                .get(&key)
                .cloned()
                .unwrap_or_else(|| module_name(&key)),
            depth,
        })
        .collect();
    out.sort();
    out
}

/// The record for one easyconfigs pull request, or `None` when it carries no
/// easyconfig changes.
pub fn easyconfig_record(
    pr: &PrInput,
    base: &[Candidate],
    installed: Option<&BTreeSet<String>>,
    config: &OverlapConfig,
) -> Option<PrRecord> {
    if pr.easyconfigs.is_empty() {
        return None;
    }
    let overlay = overlay_easyconfigs(base, &pr.easyconfigs);
    let mut universe = overlay.tree.clone();
    if !config.filter_deps.is_empty() {
        config.filter_deps.apply(&mut universe);
    }
    let closure = closure_against_installed(&universe, &overlay.starts, Choice::Newest, &|_| false);
    let mut unresolved = overlay.unresolved;
    let kept = retain_resolved_easyblocks(
        &closure.to_build,
        &universe,
        config.easyblocks.as_ref(),
        &BTreeSet::new(),
        &mut unresolved,
    );
    for requirement in closure.unresolved {
        unresolved.insert(format!(
            "{} needs {}",
            module_name(&requirement.from),
            requirement.requirement
        ));
    }
    let mut reached: Vec<String> = kept.iter().map(module_name).collect();
    reached.sort();
    reached.dedup();
    let base_modules: BTreeSet<String> = base.iter().map(module_of).collect();
    let new_modules: Vec<String> = reached
        .iter()
        .filter(|module| !base_modules.contains(*module))
        .cloned()
        .collect();
    let (to_build, already_installed) = match installed {
        Some(installed) => {
            let to_build: Vec<String> = reached
                .iter()
                .filter(|module| !installed.contains(*module))
                .cloned()
                .collect();
            let already: Vec<String> = reached
                .iter()
                .filter(|module| installed.contains(*module))
                .cloned()
                .collect();
            (to_build, already)
        }
        None => (new_modules.clone(), Vec::new()),
    };
    Some(PrRecord {
        schema_version: EASYCONFIG_PR_SCHEMA_VERSION,
        pr: pr.number,
        head_sha: pr.head_sha.clone(),
        title: pr.title.clone(),
        generated_at: config.generated_at.clone(),
        eessi_version: String::new(),
        installed_source: config.installed_source.clone(),
        easystack_files: Vec::new(),
        to_build,
        already_installed,
        unresolved: unresolved.into_iter().collect(),
        notes: overlay.notes.into_iter().collect(),
        entries: Vec::new(),
        kind: "easyconfigs".to_string(),
        changed_easyconfigs: overlay.changed.clone(),
        closure: reached,
        new_modules,
        revisions: file_revisions(pr, config),
        reverse_dependents: reverse_dependents(base, &overlay.changed),
    })
}

/// One added easystack line and the easyblock source it names.
struct Start {
    file: String,
    easyblock_commit: Option<String>,
    easyblock_pr: Option<String>,
}

fn easyblock_class(candidate: &Candidate) -> String {
    candidate
        .easyblock
        .clone()
        .unwrap_or_else(|| encode_class_name(&candidate.name))
}

/// Drop modules whose easyblock class is not in the catalog.
///
/// A missing class is `easyblock <class> missing`. The module is not counted
/// as something the robot would build. Its dependencies stay: EasyBuild lists
/// those before it stops on the missing class.
fn retain_resolved_easyblocks(
    to_build: &[ModuleKey],
    universe: &[Candidate],
    catalog: Option<&EasyblockCatalog>,
    commits: &BTreeSet<String>,
    unresolved: &mut BTreeSet<String>,
) -> Vec<ModuleKey> {
    let Some(catalog) = catalog else {
        return to_build.to_vec();
    };
    if !catalog.check {
        return to_build.to_vec();
    }
    let by_key: BTreeMap<ModuleKey, &Candidate> = universe
        .iter()
        .map(|candidate| (ModuleKey::of(candidate), candidate))
        .collect();
    to_build
        .iter()
        .filter(|key| {
            let Some(candidate) = by_key.get(key) else {
                return true;
            };
            let class = easyblock_class(candidate);
            if easyblock_available(&class, catalog, commits) {
                true
            } else {
                unresolved.insert(format!("easyblock {class} missing"));
                false
            }
        })
        .cloned()
        .collect()
}

fn easyblock_available(
    class: &str,
    catalog: &EasyblockCatalog,
    commits: &BTreeSet<String>,
) -> bool {
    if catalog.base.contains_key(class) {
        return true;
    }
    commits.iter().any(|commit| {
        catalog
            .commits
            .get(commit)
            .is_some_and(|index| index.contains_key(class))
    })
}

/// Record easyblocks an entry says come from a commit or a pull request.
///
/// A class found in a commit tree that was passed in is noted on the module
/// that needs it. A commit the entry names but this run was not given is
/// noted as not provided, and does not count as resolving the class.
fn note_provided_easyblocks(
    group: &[Start],
    kept: &[ModuleKey],
    universe: &[Candidate],
    catalog: Option<&EasyblockCatalog>,
    commits: &BTreeSet<String>,
    notes: &mut BTreeSet<String>,
) {
    for start in group {
        if let Some(pull_request) = &start.easyblock_pr {
            notes.insert(format!("include-easyblocks-from-pr {pull_request}"));
        }
        if let Some(commit) = &start.easyblock_commit {
            let loaded = catalog.is_some_and(|catalog| catalog.commits.contains_key(commit));
            if !loaded {
                notes.insert(format!(
                    "include-easyblocks-from-commit {commit} not provided"
                ));
            }
        }
    }
    let Some(catalog) = catalog else {
        return;
    };
    let by_key: BTreeMap<ModuleKey, &Candidate> = universe
        .iter()
        .map(|candidate| (ModuleKey::of(candidate), candidate))
        .collect();
    for key in kept {
        let Some(candidate) = by_key.get(key) else {
            continue;
        };
        let class = easyblock_class(candidate);
        for commit in commits {
            let defines = catalog
                .commits
                .get(commit)
                .is_some_and(|index| index.contains_key(&class));
            if defines {
                notes.insert(format!(
                    "easyblock {class} from include-easyblocks-from-commit {commit}"
                ));
            }
        }
    }
}

/// One overlap between easyconfigs pull requests.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct OverlapRow {
    /// `same-file`, `same-module`, `shared-new-module`, or `depends-on`.
    pub kind: String,
    /// Pull requests that share a path or a module, ascending.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub prs: Vec<u64>,
    /// Path two pull requests both change. Empty for the other kinds.
    #[serde(default, skip_serializing_if = "String::is_empty")]
    pub path: String,
    /// Module two pull requests both add, or both list as new.
    #[serde(default, skip_serializing_if = "String::is_empty")]
    pub module: String,
    /// Pull request that adds the module, for `depends-on`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub from: Option<u64>,
    /// Pull request whose closure contains that module, for `depends-on`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub to: Option<u64>,
    /// Modules `to` takes from `from`.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub modules: Vec<String>,
}

/// Shared to-build modules across records.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct OverlapIndex {
    /// Index schema.
    pub schema_version: u32,
    /// When it was computed.
    pub generated_at: String,
    /// Stack version. Empty, and omitted, for an easyconfigs run.
    #[serde(default, skip_serializing_if = "String::is_empty")]
    pub eessi_version: String,
    /// Where the installed list came from.
    pub installed_source: String,
    /// Pull requests with a record, ascending.
    pub prs: Vec<u64>,
    /// Module to the pull requests that would build it, for modules more than
    /// one would build.
    pub shared: BTreeMap<String, Vec<u64>>,
    /// Per pull request: the other pull requests it shares modules with, and
    /// which modules, keyed by the pull request number as a string.
    pub pairs: BTreeMap<String, BTreeMap<String, Vec<String>>>,
    /// Typed overlap rows for an easyconfigs run. Empty, and omitted, for a
    /// software-layer run, which keeps the schema 1 field set.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub rows: Vec<OverlapRow>,
}

/// Intersect the to-build sets of every record.
pub fn overlap_index(records: &[PrRecord], config: &OverlapConfig) -> OverlapIndex {
    let mut by_module: BTreeMap<String, BTreeSet<u64>> = BTreeMap::new();
    for r in records {
        for m in &r.to_build {
            by_module.entry(m.clone()).or_default().insert(r.pr);
        }
    }
    let shared: BTreeMap<String, Vec<u64>> = by_module
        .into_iter()
        .filter(|(_, prs)| prs.len() > 1)
        .map(|(m, prs)| (m, prs.into_iter().collect()))
        .collect();
    let mut pairs: BTreeMap<u64, BTreeMap<u64, Vec<String>>> = BTreeMap::new();
    for (module, prs) in &shared {
        for a in prs {
            for b in prs {
                if a != b {
                    pairs
                        .entry(*a)
                        .or_default()
                        .entry(*b)
                        .or_default()
                        .push(module.clone());
                }
            }
        }
    }
    let mut prs: Vec<u64> = records.iter().map(|r| r.pr).collect();
    prs.sort_unstable();
    prs.dedup();
    let easyconfigs = records.iter().any(|record| record.kind == "easyconfigs");
    OverlapIndex {
        schema_version: if easyconfigs {
            EASYCONFIG_PR_SCHEMA_VERSION
        } else {
            PR_OVERLAP_SCHEMA_VERSION
        },
        generated_at: config.generated_at.clone(),
        eessi_version: config.eessi_version.clone(),
        installed_source: config.installed_source.clone(),
        prs,
        shared,
        pairs: pairs
            .into_iter()
            .map(|(a, m)| {
                (
                    a.to_string(),
                    m.into_iter().map(|(b, v)| (b.to_string(), v)).collect(),
                )
            })
            .collect(),
        rows: if easyconfigs {
            easyconfig_rows(records)
        } else {
            Vec::new()
        },
    }
}

fn push_grouped(
    rows: &mut Vec<OverlapRow>,
    kind: &str,
    groups: BTreeMap<String, BTreeSet<u64>>,
    path: bool,
) {
    for (key, prs) in groups {
        if prs.len() < 2 {
            continue;
        }
        let mut row = OverlapRow {
            kind: kind.to_string(),
            prs: prs.into_iter().collect(),
            path: String::new(),
            module: String::new(),
            from: None,
            to: None,
            modules: Vec::new(),
        };
        if path {
            row.path = key;
        } else {
            row.module = key;
        }
        rows.push(row);
    }
}

/// Typed overlap rows for easyconfigs pull requests.
fn easyconfig_rows(records: &[PrRecord]) -> Vec<OverlapRow> {
    let mut by_path: BTreeMap<String, BTreeSet<u64>> = BTreeMap::new();
    let mut by_added: BTreeMap<String, BTreeSet<u64>> = BTreeMap::new();
    let mut by_new: BTreeMap<String, BTreeSet<u64>> = BTreeMap::new();
    for record in records {
        for change in &record.changed_easyconfigs {
            by_path
                .entry(change.path.clone())
                .or_default()
                .insert(record.pr);
            if change.status == "added" {
                if let Some(module) = &change.module {
                    by_added
                        .entry(module.clone())
                        .or_default()
                        .insert(record.pr);
                }
            }
        }
        for module in &record.new_modules {
            by_new.entry(module.clone()).or_default().insert(record.pr);
        }
    }
    let mut rows = Vec::new();
    push_grouped(&mut rows, "same-file", by_path, true);
    push_grouped(&mut rows, "same-module", by_added, false);
    push_grouped(&mut rows, "shared-new-module", by_new, false);
    let adds = |record: &PrRecord, module: &str| {
        record
            .changed_easyconfigs
            .iter()
            .any(|change| change.status == "added" && change.module.as_deref() == Some(module))
    };
    for left in records {
        for right in records {
            if left.pr == right.pr {
                continue;
            }
            let mut modules: Vec<String> = left
                .changed_easyconfigs
                .iter()
                .filter(|change| change.status == "added")
                .filter_map(|change| change.module.clone())
                .filter(|module| {
                    right.closure.iter().any(|item| item == module) && !adds(right, module)
                })
                .collect();
            modules.sort();
            modules.dedup();
            if modules.is_empty() {
                continue;
            }
            rows.push(OverlapRow {
                kind: "depends-on".to_string(),
                prs: Vec::new(),
                path: String::new(),
                module: String::new(),
                from: Some(left.pr),
                to: Some(right.pr),
                modules,
            });
        }
    }
    rows
}

/// A record or index as TOML, with the generated-file header.
pub fn to_toml<T: Serialize>(value: &T) -> Result<String, toml::ser::Error> {
    Ok(format!("{GENERATED_HEADER}\n{}", toml::to_string(value)?))
}

/// One pull request's record, with `to_build` as one sorted line per module.
///
/// The same line in two `prs/<N>.toml` files is a module both pull requests
/// would build. `git diff` shows a deploy dropping that line, and
/// `sort | uniq -d` across the `to_build` lines is the overlap.
pub fn record_to_toml(record: &PrRecord) -> Result<String, toml::ser::Error> {
    let mut modules = record.to_build.clone();
    modules.sort();
    let mut without = record.clone();
    without.to_build.clear();
    let body = expand_to_build(&toml::to_string(&without)?, &modules);
    Ok(format!("{GENERATED_HEADER}\n{body}"))
}

/// Replace the empty `to_build` array left by [`record_to_toml`] with one
/// quoted module per line. Any other empty array is left alone.
fn expand_to_build(text: &str, modules: &[String]) -> String {
    let mut out = String::with_capacity(text.len() + modules.len() * 48);
    let mut replaced = false;
    for line in text.lines() {
        if !replaced && line == "to_build = []" {
            replaced = true;
            out.push_str(&render_to_build(modules));
            continue;
        }
        out.push_str(line);
        out.push('\n');
    }
    if !replaced {
        out.push_str(&render_to_build(modules));
    }
    out
}

fn render_to_build(modules: &[String]) -> String {
    if modules.is_empty() {
        return "to_build = []\n".to_string();
    }
    let mut out = String::from("to_build = [\n");
    for module in modules {
        out.push_str("  \"");
        out.push_str(&module.replace('\\', "\\\\").replace('"', "\\\""));
        out.push_str("\",\n");
    }
    out.push_str("]\n");
    out
}

/// The overlap report for reviewers, as Markdown.
///
/// Pull requests are written as plain `#N` text inside a file, which links on
/// GitHub without adding anything to the pull requests' timelines.
pub fn render_markdown(records: &[PrRecord], index: &OverlapIndex, repo_url: &str) -> String {
    let link = |n: u64| {
        if repo_url.is_empty() {
            format!("#{n}")
        } else {
            format!("[#{n}]({}/pull/{n})", repo_url.trim_end_matches('/'))
        }
    };
    let mut out = String::new();
    out.push_str("<!-- Generated by `eb-stack pr-overlap`. This branch is never merged. -->\n");
    out.push_str(&format!(
        "# Shared builds between open pull requests ({})\n\n",
        index.eessi_version
    ));
    out.push_str(&format!(
        "Computed {} against the modules installed for `{}`. {} pull requests change an easystack for this version.\n\n",
        index.generated_at,
        index.installed_source,
        records.len()
    ));
    out.push_str("## Modules more than one pull request would build\n\n");
    if index.shared.is_empty() {
        out.push_str("None.\n\n");
    } else {
        out.push_str("| Module | Pull requests |\n|---|---|\n");
        for (module, prs) in &index.shared {
            let prs: Vec<String> = prs.iter().map(|n| link(*n)).collect();
            out.push_str(&format!("| `{module}` | {} |\n", prs.join(", ")));
        }
        out.push('\n');
    }
    out.push_str("## Per pull request\n\n");
    let mut sorted: Vec<&PrRecord> = records.iter().collect();
    sorted.sort_by_key(|r| r.pr);
    for r in sorted {
        let short: String = r.head_sha.chars().take(10).collect();
        out.push_str(&format!(
            "### {} {} (`{short}`)\n\n",
            link(r.pr),
            r.title.as_deref().unwrap_or("")
        ));
        out.push_str(&format!(
            "Builds {} modules; {} reached modules are already installed.\n\n",
            r.to_build.len(),
            r.already_installed.len()
        ));
        if let Some(others) = index.pairs.get(&r.pr.to_string()) {
            for (other, modules) in others {
                let n: u64 = other.parse().unwrap_or_default();
                let list: Vec<String> = modules.iter().map(|m| format!("`{m}`")).collect();
                out.push_str(&format!(
                    "- shares {} with {}: {}\n",
                    modules.len(),
                    link(n),
                    list.join(", ")
                ));
            }
        } else {
            out.push_str("- shares nothing with another open pull request\n");
        }
        for u in &r.unresolved {
            out.push_str(&format!("- unresolved: {u}\n"));
        }
        for note in &r.notes {
            out.push_str(&format!("- note: {note}\n"));
        }
        out.push_str("\n<details><summary>To build</summary>\n\n");
        for m in &r.to_build {
            out.push_str(&format!("- `{m}`\n"));
        }
        out.push_str("\n</details>\n\n");
    }
    out
}

