        let dep_path = "easybuild/easyconfigs/d/Dep/Dep-1.0.eb";
        let app_path = "easybuild/easyconfigs/a/App/App-1.0.eb";
        let base = vec![parsed(dep_path, &eb("Dep", "1.0", None))];
