//! Which open pull requests to a software layer would build the same modules.
//!
//! A software-layer pull request adds lines to an easystack, and what it really
//! asks for is everything `eb --easystack <file> --robot` would install for
//! those lines on the current stack: the named easyconfigs plus every
//! dependency not installed yet. Two pull requests that both need a module
//! nobody has built will both build it, and the reviewer who has to order
//! them works that out by hand today.
//!
//! This module answers it from the recipes alone, with no build and no
//! model. Per pull request it reads the easystack entries the change adds,
//! finds their easyconfigs on the robot path (the release tree plus, for an
//! entry pinned with `from-commit`, the easyconfigs tree at that commit ahead
//! of it), and closes
//! them with [`crate::build_order::closure_against_installed`] against the list
//! of installed modules. An installed module is a leaf, as it is for the robot.
//! The overlap report is then a set intersection over the to-build sets.
//!
//! The pull request's files are read as data. Nothing from a pull request is
//! executed, which is what lets a scheduled job on the base repository run
//! this over pull requests from forks.

use crate::build_order::{closure_against_installed, module_name, Choice, ModuleKey};
use crate::dep_filter::FilterDeps;
use crate::domain::Candidate;
use crate::easystack::{parse_easystack_entries, EasystackEntry};
use crate::eb_easyblock::encode_class_name;
