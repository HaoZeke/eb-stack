//! `eb-stack component-reach` writes the three report files.

use std::path::Path;
use std::process::Command;

#[test]
fn the_cli_writes_toml_json_and_markdown() {
    let dir = tempfile::tempdir().expect("temp");
    let root = dir.path();
    std::fs::write(
        root.join("cURL.eb"),
        "name = 'cURL'\nversion = '8.17.0'\ntoolchain = {'name': 'GCCcore', 'version': '15.2.0'}\n",
    )
    .unwrap();
    std::fs::write(
        root.join("git.eb"),
        "name = 'git'\nversion = '2'\ntoolchain = {'name': 'GCCcore', 'version': '15.2.0'}\ndependencies = [('cURL', '8.17.0')]\n",
    )
    .unwrap();
    std::fs::write(root.join("compat.txt"), "curl 8.17.0\n").unwrap();
    let out = root.join("out");
    let output = Command::new(env!("CARGO_BIN_EXE_eb-stack"))
        .env_remove("EASYBUILD_FILTER_DEPS")
        .args([
            "component-reach",
            "--component",
            "curl",
            "--version",
            "*",
            "--generation",
            "2026.1",
            "--easyconfigs",
        ])
        .arg(root)
        .args(["--compat-layer"])
        .arg(root.join("compat.txt"))
        .args(["--generated-at", "2026-10-22T12:00:00Z", "--out-dir"])
        .arg(&out)
        .output()
        .expect("run");
    assert!(
        output.status.success(),
        "{}",
        String::from_utf8_lossy(&output.stderr)
    );
    let stdout = String::from_utf8(output.stdout).unwrap();
    assert!(stdout.contains("carriers=3"), "{stdout}");
    let json: serde_json::Value =
        serde_json::from_str(&std::fs::read_to_string(out.join("component-reach.json")).unwrap())
            .unwrap();
    assert_eq!(json["schema_version"], 1);
    assert_eq!(json["component"], "curl");
    assert!(json["closure_counts"]["no-rebuild"].as_u64().unwrap() >= 1);
    let toml = std::fs::read_to_string(out.join("component-reach.toml")).unwrap();
    assert!(toml.starts_with("# Generated by `eb-stack component-reach`.\n"));
    let md = std::fs::read_to_string(out.join("component-reach.md")).unwrap();
    assert!(md.contains("| Easyconfig | Module | Role | Version | Installed |"));
    assert!(Path::new(&out.join("component-reach.md")).is_file());
}
