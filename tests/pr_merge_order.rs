//! `eb-stack pr-overlap --merge-order` on the shared fixtures, plus three
//! pull requests: 11 and 13 add freetype, 12 adds Graphviz (which reaches it).

use std::path::{Path, PathBuf};
use std::process::Command;

const STACK: &str = "easystacks/software.eessi.io/2026.06/eessi-2026.06-eb-5.4.0-2026.1.yml";

const EXPECTED: &str = r#"# Generated by `eb-stack pr-overlap`. Data only: the branch holding this file is
# regenerated on every run and must never be merged.

schema_version = 1
generated_at = "2026-10-22T00:00:00Z"
installed_source = "x86_64/amd/zen4"
merged = []
cycles = []

[[steps]]
position = 1
pr = 11
after = []
builds = ["freetype/2.14.1-GCCcore-15.2.0", "libpng/1.6.50-GCCcore-15.2.0"]
reason = "smallest residual build set (2)"

[[steps.saves]]
pr = 12
modules = ["freetype/2.14.1-GCCcore-15.2.0", "libpng/1.6.50-GCCcore-15.2.0"]

[[steps.saves]]
pr = 13
modules = ["freetype/2.14.1-GCCcore-15.2.0", "libpng/1.6.50-GCCcore-15.2.0"]

[[steps]]
position = 2
pr = 13
after = []
builds = []
saves = []
reason = "smallest residual build set (0)"

[[steps]]
position = 3
pr = 12
after = [11, 13]
builds = ["Graphviz/14.0.2-GCCcore-15.2.0"]
saves = []
reason = "smallest residual build set (1)"

[[conflicts]]
easystack = "easystacks/software.eessi.io/2026.06/eessi-2026.06-eb-5.4.0-2026.1.yml"
prs = [11, 13]
kind = "same-entry"

[[conflicts]]
easystack = "easystacks/software.eessi.io/2026.06/eessi-2026.06-eb-5.4.0-2026.1.yml"
prs = [11, 12, 13]
kind = "same-insertion"
"#;

fn fixtures() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/pr_overlap_fixtures")
}

fn prs_json() -> String {
    let base = "easyconfigs:\n  - zlib-1.3.1-GCCcore-15.2.0.eb\n";
    let one = |n: u64, added: &str| {
        serde_json::json!({
            "number": n,
            "head_sha": format!("{n:040}"),
            "title": format!("PR {n}"),
            "easystacks": [{
                "path": STACK,
                "base": base,
                "head": format!("{base}{added}"),
            }],
        })
    };
    serde_json::to_string(&vec![
        one(11, "  - freetype-2.14.1-GCCcore-15.2.0.eb\n"),
        one(12, "  - Graphviz-14.0.2-GCCcore-15.2.0.eb\n"),
        one(13, "  - freetype-2.14.1-GCCcore-15.2.0.eb\n"),
    ])
    .expect("json")
}

fn run(bin: &str, input: &Path, out: &Path, extra: &[&str]) -> std::process::Output {
    Command::new(bin)
        .env_remove("EASYBUILD_FILTER_DEPS")
        .args(["pr-overlap", "--pr"])
        .arg(input)
        .arg("--easyconfigs")
        .arg(fixtures().join("release"))
        .arg("--installed")
        .arg(fixtures().join("installed.txt"))
        .args(["--installed-label", "x86_64/amd/zen4"])
        .args(["--generated-at", "2026-10-22T00:00:00Z"])
        .args(["--repo-url", "https://github.com/EESSI/software-layer"])
        .arg("--out-dir")
        .arg(out)
        .args(extra)
        .output()
        .expect("run")
}

#[test]
fn merge_order_toml_is_exact_and_the_old_files_do_not_change() {
    let bin = env!("CARGO_BIN_EXE_eb-stack");
    let temp = tempfile::tempdir().expect("temp");
    let input = temp.path().join("prs.json");
    std::fs::write(&input, prs_json()).expect("write json");
    let plain = temp.path().join("plain");
    let ordered = temp.path().join("ordered");
    let status = run(bin, &input, &plain, &[]);
    assert!(
        status.status.success(),
        "{}",
        String::from_utf8_lossy(&status.stderr)
    );
    let status = run(bin, &input, &ordered, &["--merge-order"]);
    assert!(
        status.status.success(),
        "{}",
        String::from_utf8_lossy(&status.stderr)
    );
    for name in ["overlap.toml", "prs/11.toml", "prs/12.toml", "prs/13.toml"] {
        let left = std::fs::read(plain.join(name)).expect(name);
        let right = std::fs::read(ordered.join(name)).expect(name);
        assert_eq!(left, right, "{name}");
    }
    assert!(!plain.join("merge-order.toml").exists());
    let plain_md = std::fs::read_to_string(plain.join("overlap.md")).expect("md");
    let ordered_md = std::fs::read_to_string(ordered.join("overlap.md")).expect("md");
    assert!(ordered_md.starts_with(&plain_md));
    assert!(ordered_md.contains("## Merge order"));
    let got = std::fs::read_to_string(ordered.join("merge-order.toml")).expect("toml");
    assert_eq!(got, EXPECTED);

    let merged = temp.path().join("merged");
    let status = run(bin, &input, &merged, &["--merged", "11"]);
    assert!(
        status.status.success(),
        "{}",
        String::from_utf8_lossy(&status.stderr)
    );
    let text = std::fs::read_to_string(merged.join("merge-order.toml")).expect("toml");
    assert!(text.contains("merged = [11]\n"), "{text}");
    assert!(!text.contains("pr = 11\n"), "{text}");

    let bad = run(bin, &input, &temp.path().join("bad"), &["--merged", "999"]);
    assert!(!bad.status.success());
    let err = String::from_utf8_lossy(&bad.stderr);
    assert!(
        err.contains("--merged 999: no pull request with that number"),
        "{err}"
    );

    let impact_dir = temp.path().join("impact");
    let status = run(bin, &input, &impact_dir, &["--impact", "11"]);
    assert!(
        status.status.success(),
        "{}",
        String::from_utf8_lossy(&status.stderr)
    );
    let text = std::fs::read_to_string(impact_dir.join("merge-impact.toml")).expect("impact");
    assert!(text.starts_with("# Generated by `eb-stack pr-overlap`."));
    let report: eb_stack::merge_order::MergeImpactReport = toml::from_str(&text).expect("parse");
    assert_eq!(report.impacts.len(), 1);
    assert_eq!(report.impacts[0].pr, 11);
    let by_pr = report.impacts[0]
        .affected
        .iter()
        .map(|effect| (effect.pr, effect.shrinks.clone(), effect.resolves.clone()))
        .collect::<Vec<_>>();
    assert_eq!(
        by_pr,
        vec![
            (
                12,
                vec![
                    "freetype/2.14.1-GCCcore-15.2.0".into(),
                    "libpng/1.6.50-GCCcore-15.2.0".into(),
                ],
                vec!["freetype/2.14.1-GCCcore-15.2.0".into()],
            ),
            (
                13,
                vec![
                    "freetype/2.14.1-GCCcore-15.2.0".into(),
                    "libpng/1.6.50-GCCcore-15.2.0".into(),
                ],
                vec![],
            ),
        ]
    );
    assert!(!impact_dir.join("merge-order.toml").exists());
    let unknown = run(
        bin,
        &input,
        &temp.path().join("impact-bad"),
        &["--impact", "999"],
    );
    assert!(!unknown.status.success());
    let err = String::from_utf8_lossy(&unknown.stderr);
    assert!(
        err.contains("--impact 999: no pull request with that number"),
        "{err}"
    );
}

#[test]
fn rejected_merged_and_impact_leave_the_output_untouched() {
    let bin = env!("CARGO_BIN_EXE_eb-stack");
    let temp = tempfile::tempdir().expect("temp");
    let input = temp.path().join("prs.json");
    std::fs::write(&input, prs_json()).expect("write json");

    let fresh = temp.path().join("fresh");
    let bad = run(bin, &input, &fresh, &["--impact", "999"]);
    assert_eq!(bad.status.code(), Some(2));
    let err = String::from_utf8_lossy(&bad.stderr);
    assert!(
        err.contains("--impact 999: no pull request with that number"),
        "{err}"
    );
    let fresh_files = if fresh.exists() {
        std::fs::read_dir(&fresh).unwrap().count()
    } else {
        0
    };
    assert_eq!(
        fresh_files, 0,
        "fresh --out-dir was written on a usage error"
    );

    let kept = temp.path().join("kept");
    let ok = run(bin, &input, &kept, &[]);
    assert!(
        ok.status.success(),
        "{}",
        String::from_utf8_lossy(&ok.stderr)
    );
    let marker = kept.join("prs").join("99.toml");
    std::fs::write(&marker, "keep\n").unwrap();
    let before = std::fs::read(kept.join("overlap.toml")).unwrap();
    let bad = run(bin, &input, &kept, &["--merged", "999"]);
    assert_eq!(bad.status.code(), Some(2));
    assert_eq!(std::fs::read_to_string(&marker).unwrap(), "keep\n");
    assert_eq!(std::fs::read(kept.join("overlap.toml")).unwrap(), before);
}
